export function getError(code: string, fallback?: string): string {
  const normalized = (code || "").toLowerCase();
  const errorMap: Record<string, string> = {
    insufficient_credits: "DetectifAI credit balance is insufficient for this request.",
    invalid_api_key: "Backend DetectifAI API key was rejected as invalid.",
    rate_limited: "Rate limit reached. Please wait a moment before retrying.",
    server_busy: "Analysis server is temporarily busy. Please retry shortly.",
    audio_too_short: "Audio clip is too short for reliable analysis.",
    insufficient_speech: "Insufficient speech detected in the audio sample.",
    speaker_not_found: "No matching enrolled speaker profile was found.",
    too_many_samples: "Maximum enrollment audio sample limit reached for this speaker.",
    upload_timeout: "Audio upload timed out before completing.",
    unexpected_response: "Unexpected response from backend",
    aletheia_unavailable: "Aletheia voice authenticity service is temporarily unavailable.",
    eidos_unavailable: "Eidos speaker identity service is temporarily unavailable.",
    unauthorized: "Missing or invalid platform authorization credentials.",
    invalid_payload: "Invalid request payload format. Check audio format and parameters.",
    network_error: "Unable to connect to the AEGIS analysis gateway.",
    not_found: "The requested resource was not found.",
  };
  return errorMap[normalized] || fallback || COPY.states.errorTitle;
}
